#!/bin/sh
# Pre-launch gate for nginx (HTTP Basic).
#
#   ./scripts/gen-entry.sh          # read ENTRY_USER/ENTRY_PASS from .env
#
# Writes:
#   nginx/htpasswd   — apr1 hash of the password (never the plain password)
#   nginx/auth.conf  — auth_basic directives, or a comment when the gate is open
#
# Both files are mounted into the nginx container (see docker-compose.yml), so
# the site keeps its html/assets even while the backend restarts. Empty
# ENTRY_USER / ENTRY_PASS in .env means "launched": the gate is open.
set -e
cd "$(dirname "$0")/.."

user=$(grep -E '^ENTRY_USER=' .env | cut -d= -f2- || true)
pass=$(grep -E '^ENTRY_PASS=' .env | cut -d= -f2- || true)
mkdir -p nginx

if [ -n "$user" ] && [ -n "$pass" ]; then
  hash=$(openssl passwd -apr1 "$pass")
  printf '%s:%s\n' "$user" "$hash" > nginx/htpasswd
  cat > nginx/auth.conf <<EOF
# generated by scripts/gen-entry.sh — pre-launch gate (HTTP Basic)
#
# satisfy any + allow <private ranges>: requests from this machine / LAN open
# without a prompt (dev, phone on the same wifi), while visitors from the
# internet must log in. NOTE: if your prod nginx sits behind a proxy that
# makes every client look private, drop the allow lines and keep auth only.
satisfy any;
allow 127.0.0.1;
allow ::1;
allow 10.0.0.0/8;
allow 172.16.0.0/12;
allow 192.168.0.0/16;
deny all;
auth_basic "The Internet Void — local preview";
auth_basic_user_file /etc/nginx/.htpasswd;
EOF
  echo "gate: ON  (user: $user)"
else
  : > nginx/htpasswd
  printf '%s\n' '# generated by scripts/gen-entry.sh — gate open, site is launched' > nginx/auth.conf
  echo "gate: OFF (ENTRY_USER/ENTRY_PASS empty — the site is public)"
fi
